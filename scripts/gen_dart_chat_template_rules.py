#!/usr/bin/env python3
"""Generates lib/models/chat_template_rules.g.dart from scripts/chat_template_rules.json.
  python3 -I scripts/gen_dart_chat_template_rules.py          # write
  python3 -I scripts/gen_dart_chat_template_rules.py --check  # exit 1 if the .g.dart is stale
"""
import json, os, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
doc = json.load(open(os.path.join(ROOT, "scripts", "chat_template_rules.json"), encoding="utf-8"))
def lit(s):  # Dart single-quoted raw-safe literal using unicode escapes only where needed
    out = []
    for ch in s:
        if ch == "\\": out.append("\\\\")
        elif ch == "'": out.append("\\'")
        elif ch == "$": out.append("\\$")
        elif ch == "\n": out.append("\\n")
        else: out.append(ch)
    return "'" + "".join(out) + "'"
L = ["// GENERATED by scripts/gen_dart_chat_template_rules.py from scripts/chat_template_rules.json - DO NOT EDIT.",
     f"// Mirrors llm_chat_detect_template() of llama.cpp {doc['pinnedCommit']}.",
     "// ignore_for_file: lines_longer_than_80_chars",
     "",
     f"const String kChatTemplateRulesCommit = {lit(doc['pinnedCommit'])};",
     "",
     "class ChatTemplateRule {",
     "  const ChatTemplateRule(this.family, {this.all = const [], this.any = const []});",
     "  final String family;",
     "  final List<String> all; // every marker must be present",
     "  final List<String> any; // at least one marker must be present",
     "}", "",
     "const List<String> kChatTemplateNames = [" ]
L += [f"  {lit(n)}," for n in doc["names"]]
L += ["];", "", "const List<String> kChatTemplatePrefixes = [" ]
L += [f"  {lit(p)}," for p in doc["prefixes"]]
L += ["];", "", "const List<ChatTemplateRule> kChatTemplateRules = ["]
for r in doc["rules"]:
    parts = [lit(r["family"])]
    if "all" in r: parts.append("all: [" + ", ".join(lit(m) for m in r["all"]) + "]")
    if "any" in r: parts.append("any: [" + ", ".join(lit(m) for m in r["any"]) + "]")
    L.append(f"  ChatTemplateRule({', '.join(parts)}),")
L += ["];", ""]
text = "\n".join(L)
path = os.path.join(ROOT, "lib", "models", "chat_template_rules.g.dart")
if "--check" in sys.argv:
    cur = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
    print("up to date" if cur == text else "STALE: regenerate"); sys.exit(0 if cur == text else 1)
open(path, "w", encoding="utf-8").write(text); print("wrote", path)
